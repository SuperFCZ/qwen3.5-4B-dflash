"""Sanitized fixtures for the observed CMake 3.16 dependency record formats."""
import json,shlex,sys
from pathlib import Path
import pytest
HERE=Path(__file__).resolve().parents[1];sys.path.insert(0,str(HERE))
import dependency_identity as d


def escaped(value):
 return str(value).replace('\\','\\\\').replace('$','$$').replace(' ','\\ ').replace('#','\\#').replace(':','\\:')


def fixture(tmp_path,relative=False,space=False):
 root=tmp_path/('sdk space' if space else 'sdk');real=root/'actual/platform_ascendc.h';real.parent.mkdir(parents=True);real.write_text('reviewed CPU fixture')
 alias=root/'include/tiling/platform/platform_ascendc.h';alias.parent.mkdir(parents=True);alias.symlink_to(real)
 build=tmp_path/'build';target=build/'CMakeFiles/stage4i_host.dir';target.mkdir(parents=True)
 obj=target/'probe.cpp.o';obj.write_bytes(b'CPU object fixture')
 source=tmp_path/'source/probe.cpp';source.parent.mkdir();source.write_text('// CPU fixture')
 command=['/usr/bin/c++','-I'+str(root/'include'),'-O2','-std=gnu++17','-o','CMakeFiles/stage4i_host.dir/probe.cpp.o','-c',str(source)]
 (build/'compile_commands.json').write_text(json.dumps([dict(directory=str(build),file=str(source),command=shlex.join(command))]))
 (build/'CMakeCache.txt').write_text('CMAKE_GENERATOR:INTERNAL=Unix Makefiles\nCMAKE_MAKE_PROGRAM:FILEPATH=/usr/bin/make\n')
 (target/'DependInfo.cmake').write_text('set(CMAKE_DEPENDS_CHECK_CXX\n "'+str(source)+'" "'+str(obj)+'"\n )\n')
 paths=[str(source),str(alias)]
 if relative:paths=['../source/probe.cpp','../'+root.name+'/include/tiling/platform/platform_ascendc.h']
 header='# CMAKE generated file: DO NOT EDIT!\n# Generated by "Unix Makefiles" Generator, CMake Version 3.16\n\n'
 name='CMakeFiles/stage4i_host.dir/probe.cpp.o'
 (target/'depend.make').write_text(header+''.join(name+': '+escaped(p)+'\n' for p in paths))
 (target/'depend.internal').write_text(header+name+'\n'+''.join(' '+p+'\n' for p in paths))
 return build,root,source,d.identity(real),target,alias

@pytest.mark.parametrize('relative,space',[(False,False),(True,False),(True,True)])
def test_observed_make_pair_and_exact_symlink_identity(tmp_path,relative,space):
 build,cann,source,reviewed,target,alias=fixture(tmp_path,relative,space)
 assert not list(build.rglob('*.o.d'))
 result=d.compiled_dependencies(build,cann,source,reviewed)
 assert result['route']=='CMAKE_UNIX_MAKEFILES_IMPLICIT_DEPENDENCIES'
 assert result['headers']==[reviewed] and result['platform_dependency_paths']==[str(alias)]
 assert {Path(x['path']).name for x in result['evidence']}=={'compile_commands.json','CMakeCache.txt','DependInfo.cmake','depend.make','depend.internal'}
 d.verify_dependency_binding(result)

@pytest.mark.parametrize('fault',['missing','wrong_target','wrong_mapping','disagree','wrong_same_name','escaped_sdk_link','tampered_header','missing_object'])
def test_fail_closed(tmp_path,fault):
 build,cann,source,reviewed,target,alias=fixture(tmp_path)
 if fault=='missing':(target/'depend.internal').unlink()
 elif fault=='wrong_target':
  for name in ('depend.make','depend.internal'):
   p=target/name;p.write_text(p.read_text().replace('probe.cpp.o','other.cpp.o'))
 elif fault=='wrong_mapping':
  p=target/'DependInfo.cmake';p.write_text(p.read_text().replace('probe.cpp"','different.cpp"'))
 elif fault=='disagree':
  p=target/'depend.internal';p.write_text(p.read_text().replace(' '+str(alias)+'\n',''))
 elif fault in ('wrong_same_name','escaped_sdk_link'):
  p=(cann/'different/platform_ascendc.h') if fault=='wrong_same_name' else tmp_path/'outside/platform_ascendc.h'
  p.parent.mkdir();p.write_text('reviewed CPU fixture') # same bytes do not excuse another path/root
  alias.unlink();alias.symlink_to(p)
 elif fault=='tampered_header':Path(reviewed['path']).write_text('modified')
 else:(target/'probe.cpp.o').unlink()
 with pytest.raises((ValueError,OSError)):d.compiled_dependencies(build,cann,source,reviewed)


def test_alias_retarget_and_evidence_tamper_after_check(tmp_path):
 build,cann,source,reviewed,target,alias=fixture(tmp_path)
 result=d.compiled_dependencies(build,cann,source,reviewed)
 other=cann/'other.h';other.write_text('reviewed CPU fixture');alias.unlink();alias.symlink_to(other)
 with pytest.raises(ValueError,match='alias'):d.verify_dependency_binding(result)
 alias.unlink();alias.symlink_to(reviewed['path'])
 p=target/'depend.make';p.write_text(p.read_text()+'# later modification\n')
 with pytest.raises(ValueError,match='identity changed'):d.verify_dependency_binding(result)


def test_existing_compiler_depfile_bound_to_target_and_compile_directory(tmp_path):
 build,cann,source,reviewed,target,alias=fixture(tmp_path,space=True)
 dep=target/'probe.cpp.o.d';dep.write_text('CMakeFiles/stage4i_host.dir/probe.cpp.o: '+escaped(source)+' \\\n '+escaped(alias)+'\n'+escaped(alias)+':\n')
 result=d.compiled_dependencies(build,cann,source,reviewed)
 assert result['route']=='COMPILER_DEPFILE' and result['headers']==[reviewed]
 dep.write_text('other.o: '+escaped(source)+' '+escaped(alias)+'\n')
 with pytest.raises(ValueError,match='exact probe object'):d.compiled_dependencies(build,cann,source,reviewed)


def test_no_inference_from_include_path_or_filename(tmp_path):
 build,cann,source,reviewed,target,alias=fixture(tmp_path)
 for name in ('depend.make','depend.internal'):
  p=target/name;p.write_text(p.read_text().replace(str(alias),'').replace(': \n',':\n'))
 with pytest.raises(ValueError,match='absent'):d.compiled_dependencies(build,cann,source,reviewed)


def test_unsupported_make_expansion_never_evaluated():
 with pytest.raises(ValueError,match='expansion'):d.make_words('obj: $(shell unsafe)')
 assert d.make_words('obj: a\\ b.h x\\#y.h dollar$$.h')==['obj',None,'a b.h','x#y.h','dollar$.h']
