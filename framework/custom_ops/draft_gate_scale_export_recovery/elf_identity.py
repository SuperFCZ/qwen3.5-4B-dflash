"""Compare actual embedded dav_m200 executables, including relocations, metadata, and symbols."""

import hashlib
import re
import struct

from archive import require
from w16_static import sections

EH = struct.Struct("<16sHHIQQQIHHHHHH")
PH = struct.Struct("<IIQQQQQQ")
SH = struct.Struct("<IIQQQQIIQQ")
SYM = struct.Struct("<IBBHQQ")


def sha(data):
    return hashlib.sha256(data).hexdigest()


def string_at(table, at):
    require(0 <= at < len(table), "invalid ELF string index")
    end = table.find(b"\0", at)
    require(end >= at, "unterminated ELF string")
    return table[at:end]


def disjoint(a, b, c, d):
    return a >= b or c >= d or b <= c or d <= a


def source_tag(blob, symbol):
    """Locate digits of a non-loaded, local STT_FILE generated by the pinned CANN compiler."""
    header = EH.unpack_from(blob)
    rows = sections(blob)
    require(
        header[1:4] == (2, 4137, 1)
        and header[8] == EH.size
        and header[9] == PH.size
        and header[5] + header[9] * header[10] <= len(blob),
        "unsupported executable/program header",
    )
    by = {s["name"]: i for i, s in enumerate(rows)}
    require(len(by) == len(rows) and ".strtab" in by and ".symtab" in by, "missing/duplicate symbol tables")
    stidx, symidx = by[".strtab"], by[".symtab"]
    st, sym = rows[stidx], rows[symidx]
    require(
        st["type"] == 3
        and st["flags"] == st["va"] == 0
        and stidx != header[13]
        and sym["type"] == 2
        and sym["flags"] == 0
        and sym["link"] == stidx
        and sym["entry_size"] == SYM.size
        and sym["bytes"] % SYM.size == 0
        and [i for i, s in enumerate(rows) if s["link"] == stidx] == [symidx],
        "string table has a consumer other than the local symbol table",
    )
    start = st["offset"]
    end = start + st["bytes"]
    extents = [(0, EH.size), (header[5], header[5] + header[9] * header[10]), (header[6], len(blob))]
    extents.extend(
        (s["offset"], s["offset"] + s["bytes"]) for i, s in enumerate(rows) if i != stidx and s["type"] != 8
    )
    for i in range(header[10]):
        ph = PH.unpack_from(blob, header[5] + i * PH.size)
        require(ph[2] + ph[5] <= len(blob), "invalid program file range")
        extents.append((ph[2], ph[2] + ph[5]))
    require(all(disjoint(start, end, a, b) for a, b in extents), "mapped or overlapping ELF string table")
    table = blob[start:end]
    require(table.startswith(b"\0") and table.endswith(b"\0"), "invalid ELF string table")
    prefix, sep, suffix = symbol.rpartition("__kernel")
    require(sep and suffix.isdecimal() and prefix, "unbound ATC entry symbol")
    pattern = re.compile(re.escape(prefix.encode()) + rb"_([1-9][0-9]{0,9})_kernel\.cpp\Z")
    syms = list(SYM.iter_unpack(blob[sym["offset"] : sym["offset"] + sym["bytes"]]))
    matches = []
    for idx, (name, info, other, section, value, size) in enumerate(syms):
        tag = string_at(table, name)
        m = pattern.fullmatch(tag)
        if m:
            require(
                (info, other, section, value, size) == (4, 0, 0xFFF1, 0, 0)
                and name > 0
                and table[name - 1] == 0,
                "compiler label is not a local absolute STT_FILE",
            )
            matches.append((idx, name + m.start(1), name + m.end(1), tag.decode()))
    require(len(matches) == 1, "expected one entry-bound SDK STT_FILE")
    idx, lo, hi, filename = matches[0]
    for j, (offset, *_) in enumerate(syms):
        if j != idx:
            require(
                disjoint(lo, hi, offset, offset + len(string_at(table, offset))),
                "another symbol references the source tag",
            )
    return dict(
        file_symbol=filename,
        symbol_index=idx,
        tag=table[lo:hi].decode(),
        offset=start + lo,
        end=start + hi,
        strtab=stidx,
        strtab_offset=start,
        strtab_bytes=st["bytes"],
        symtab_offset=sym["offset"],
        symbols=len(syms),
        section_header=header[6],
    )


def normalized(blob, k):
    """Re-encode only the FILE digits and offsets that directly depend on their length."""
    lo, hi = k["offset"], k["end"]
    end = k["strtab_offset"] + k["strtab_bytes"]
    table_at = k["section_header"]
    require(
        table_at == (end + 7) // 8 * 8 and not any(blob[end:table_at]),
        "unsupported material after ELF source string table",
    )
    delta = hi - lo - 1
    data = bytearray(blob[:lo] + b"0" + blob[hi:end])
    data.extend(bytes((-len(data)) % 8))
    shoff = len(data)
    data.extend(blob[table_at:])
    struct.pack_into("<Q", data, 40, shoff)
    struct.pack_into("<Q", data, shoff + k["strtab"] * SH.size + 32, k["strtab_bytes"] - delta)
    require(
        k["symtab_offset"] + k["symbols"] * SYM.size <= k["strtab_offset"],
        "unsupported symbol-table placement",
    )
    for i in range(k["symbols"]):
        where = k["symtab_offset"] + i * SYM.size
        (name,) = struct.unpack_from("<I", blob, where)
        if name >= hi - k["strtab_offset"]:
            struct.pack_into("<I", data, where, name - delta)
    return bytes(data)


def equivalent(left, right, symbol):
    if left == right:
        return dict(status="EXACT_ELF", exact_elf_equal=True, sha256=sha(left))
    old, new = (source_tag(b, symbol) for b in (left, right))
    require(
        old["tag"] != new["tag"] and old["symbol_index"] == new["symbol_index"], "unexplained ELF difference"
    )
    if len(left) == len(right) and (old["offset"], old["end"]) == (new["offset"], new["end"]):
        # Includes ELF/program/section headers, padding and even unreferenced string table bytes.
        a, b = old["offset"], old["end"]
        require(left[:a] == right[:a] and left[b:] == right[b:], "ELF differs outside the compiler FILE tag")
        canonical = sha(left[:a] + b"0" * (b - a) + left[b:])
    else:
        l, r = normalized(left, old), normalized(right, new)
        require(l == r, "ELF differs after accounting for FILE digit width")
        canonical = sha(l)
    return dict(
        status="LOCAL_STT_FILE_TAG_ONLY",
        exact_elf_equal=False,
        comparison_sha256=canonical,
        raw_sha256=sha(left),
        candidate_sha256=sha(right),
        raw_tag=old,
        candidate_tag=new,
    )
