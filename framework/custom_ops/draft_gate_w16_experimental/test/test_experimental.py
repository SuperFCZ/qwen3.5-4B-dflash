    def test_exact_source_not_mode_label(self):
        name = "op_kernel/" + k.STEM + ".cpp"
        file = k.c.QUANT / name
        raw = {"generated_sources": {name: {"file": k.c.identity(file)}}}
        blob = file.read_bytes()
        host_file = k.OPS / "draft_a_core_scheduler_flow/op_host" / (k.STEM + ".cpp")
        from w16_common import render_host

        hdr = k.c.QUANT / "op_kernel" / k.HEADER
        # Use authentic Raw configuration generated by the same historical generator.
        from a3_launch import configure_build

        local = self.root / k.HEADER
        configure_build(
            local,
            self.root / "config.json",
            0,
            "batched",
            None,
            "prefetch",
            "a-ub",
            "broadcast",
            256,
            "loop",
            "raw",
        )
        self.assertTrue(hdr.is_file())
        for mode in k.DOUBLE:
            source = k.render_kernel(blob, mode)
            proj = self.put(mode + "/" + name, source)
            installed = self.put(mode + "/opp/vendors/customize/dynamic/" + k.STEM + ".cpp", source)
            self.put(mode + "/opp/vendors/customize/dynamic/" + k.HEADER, local.read_bytes())
            host = self.put(mode + "/host.cpp", render_host(host_file.read_bytes()))
            b = dict(
                variant=mode,
                opp={"install": str(self.root / mode / "opp")},
                dynamic=[installed],
                generated_sources={
                    name: {"file": proj},
                    "op_host/" + k.STEM + ".cpp": {"file": host},
                    **{s + "/" + k.HEADER: {"file": k.c.identity(local)} for s in ("op_host", "op_kernel")},
                },
            )
            self.assertEqual(k.checked_sources(mode, raw, b)["kernel"], proj)
            b["generated_sources"][name]["file"] = self.put(
                mode + "/bad.cpp", source.replace(b"op.WaitRaw();", b"/* missing wait */")
            )
            with self.assertRaises(ValueError):
                k.checked_sources(mode, raw, b)

    def plan(self):
        data = json.loads((k.OPS / "draft_w8a16_deep_profile/w16-ub-budget.json").read_text())
        blob = bytes.fromhex(data["queries"][0]["cube_hex"])
        fields = {f["name"]: struct.unpack_from("<I", blob, f["offset"])[0] for f in schema()}
        return dict(
            block_dim=8,
            assignments=[list(range(b, 304, 8)) for b in range(8)],
            cube_fields=fields,
            cube_sha256=k.CUBE_SHA,
            workspace=2097152,
            resources=dict(
                raw_banks=2,
                codes_bytes=32768,
                scale_bytes=512,
                weight_bytes=65536,
                tile_k=256,
                user_ub=109312,
                scratch=152832,
                l1_used=40960,
                l0a_used=16384,
                l0b_used=65536,
                l0c_used=4096,
                workspace=2097152,
            ),
        )

    def test_full_cube_layout_scratch_and_partition(self):
        plan = self.plan()
        regions = k.memory_contract(plan)["intervals"]
        self.assertEqual(regions["sdk"], [101120, 253952])
        self.assertEqual(regions["w1"], [66048, 98816])
        for change in (
            lambda p: p.update(block_dim=7),
            lambda p: p["resources"].update(scratch=185600),
            lambda p: p["resources"].update(l0b_used=65535),
            lambda p: p["cube_fields"].update(transLength=0),
            lambda p: p["cube_fields"].pop("dbL0C"),
            lambda p: p["assignments"][7].append(0),
            lambda p: p.update(workspace=4096),
        ):
            with self.subTest(change=change):
                p = copy.deepcopy(plan)
                change(p)
                with self.assertRaises(ValueError):
                    k.memory_contract(p)

