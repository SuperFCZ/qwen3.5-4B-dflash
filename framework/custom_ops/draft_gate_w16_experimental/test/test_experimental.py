    def test_prelaunch_or_sync_failure_stops_next_run(self):
        report = {"phase": "stress", "runs": []}
        prior = {"admit": {"status": flow.PASS["admit"]}}
        ctx = SimpleNamespace(
            built={m: {} for m in (k.SINGLE, *k.DOUBLE)},
            src={},
            models={m: {} for m in (k.SINGLE, *k.DOUBLE)},
        )

        def fail(folder, src, built, model, gear, layer, mode, i, pair, timed, r, previous):
            folder.mkdir(parents=True)
            (folder / "runner.log").write_text("FAIL: sync returned 42\n")
            r["runs"].append(dict(folder=str(folder), launch_authorized=True))
            raise RuntimeError("OM Runner failed")

        with patch.object(flow, "case_run", side_effect=fail) as runner, self.assertRaises(
            RuntimeError
        ) as err:
            flow.execute(self.root, report, ctx, prior, True)
        self.assertEqual(runner.call_count, 1)
        failure = flow.failure(self.root, report, err.exception)
        self.assertEqual(failure["runner_messages"], ["FAIL: sync returned 42"])
        self.assertEqual(failure["sync"], "NOT_CONFIRMED")
        self.assertTrue(failure["authorized"])

    def test_all_stage_transitions_fresh_pairs_and_replay(self):
        # Replace only unavailable server evidence and transport; keep the real
        # stage driver, integrity chain, variant order, sample aggregation and decision.
        old = self.root / "old"
        isa = self.root / "isa"
        root = self.root / "exp"
        self.put("old/static/report.json", b'{"history_roots":[]}')
        evidence = self.put("isa/static-audit.json", b"CPU fixture only")
        gold = self.put("frozen-y", b"CPU fixture only")
        modes = (k.SINGLE, *k.DOUBLE)
        ctx = SimpleNamespace(
            refs={},
            negative={"archive": evidence},
            src={"cases": {"16": {k.FIRST: {"golden": gold}}}},
            built={m: {} for m in modes},
            models={m: {} for m in modes},
        )

        def case(folder, src, built, model, gear, layer, mode, i, pair, timed, r, ref):
            folder.mkdir(parents=True)
            self.assertEqual(timed, ref is not None and pair in ("schedule", "net"))
            samples = [1.0 if mode == k.OVERLAP else 1.1] * 30
            row = dict(
                gear=gear,
                layer=layer,
                pair=pair,
                round=i,
                mode=mode,
                folder=str(folder),
                outputs={"y": [gold] * (4 if timed else 2)},
                profiled=False,
                bit_mismatches=0,
                launch_authorized=True,
                atc_plan={"block_dim": 8},
                validation=dict(
                    workspace_bytes=32,
                    model_weight_bytes=64,
                    timing={"samples_ms": samples} if timed else None,
                ),
            )
            for name in (
                "runner",
                "om",
                "opp_root",
                "opp_kernel",
                "manifest",
                "selected_kernels",
                "inputs",
                "golden",
                "air",
                "deployment",
                "frozen_constants",
            ):
                row[name] = mode
            r["runs"].append(row)

        def step(s):
            return flow.main(
                SimpleNamespace(phase=s, root=root, archive=old, isa_audit=isa, allow_device=s in flow.DEVICE)
            )

        with ExitStack() as st, redirect_stdout(io.StringIO()):
            for name, value in (
                ("load_context", ctx),
                ("compiler_evidence", {}),
                ("safety_case", {"scope": "fixture"}),
                ("cpu_witness", {}),
                ("verify_cpu", None),
                ("verify_runtime_row", None),
            ):
                st.enter_context(patch.object(flow, name, return_value=value))
            runner = st.enter_context(patch.object(flow, "case_run", side_effect=case))
            for s in flow.STAGES:
                self.assertEqual(step(s), 0, s)
            self.assertEqual(runner.call_count, 21)
        result = json.loads((root / "compare/report.json").read_text())
        self.assertEqual(result["comparison"]["decision"], "GO")
        for pair in ("schedule", "net"):
            for v in result["comparison"][pair]["variants"].values():
                self.assertEqual(len(v["samples_ms"]), 90)
        self.assertEqual(result["labels"], k.LABELS)

